const como = async (clube, janela) => { await db.exec(`select set_config('teste.eu', '${clube}', false), set_config('teste.janela', '${janela}', false)`); };
const erro = async (s, re) => { await assert.rejects(db.query(s), re); };
const jog = async id => (await q(`select * from jogadores where id = $1`, [id]))[0];

// venda ao agente: vai para a vitrine (criada agora, no grupo X), mínimo = maior entre o que o agente pagou e 3× o mercado
assert.match((await q(`select vender_pelo_agente(100) as m`))[0].m, /vitrine/);
const vit = (await q(`select vitrine from ligas where id = 1`))[0].vitrine;
assert.ok(vit);
assert.deepEqual(await q(`select grupo, dono from clubes where id = $1`, [vit]), [{ grupo: "X", dono: null }]);
let j = await jog(100);
assert.equal(j.clube_id, +vit); assert.equal(j.vitrine_minimo, 3000); assert.equal(j.vitrine_dono, U1);
await q(`select vender_pelo_agente(101)`); // o agente pagou 3200 > 3 × 800
assert.equal((await jog(101)).vitrine_minimo, 3200);
await q(`select vender_pelo_agente(102)`);
assert.equal((await q(`select count(*)::int as n from clubes where grupo = 'X'`))[0].n, 1, "uma vitrine só");

// a vitrine não sai por fora (multa, proposta): o gatilho do guardado barra
await erro(`update jogadores set clube_id = 2 where id = 100`, /guardado/);

// lances
await como(2, ""); await erro(`select dar_lance_vitrine(100, 3000, 1000, 2)`, /janela/);
await como(1, "meio"); await erro(`select dar_lance_vitrine(100, 3000, 1000, 2)`, /vendeu/);
await como(4, "meio"); await erro(`select dar_lance_vitrine(100, 3000, 1000, 2)`, /vendeu/); // outro clube do mesmo dono
await como(2, "meio"); await erro(`select dar_lance_vitrine(100, 2999, 1000, 2)`, /mínimo é de 3000/);
await erro(`select dar_lance_vitrine(100, 3000, 999, 2)`, /pelo menos 1000/);
await erro(`select dar_lance_vitrine(100, 9001, 1000, 2)`, /caixa/);
await q(`select dar_lance_vitrine(100, 3000, 1000, 2)`);
assert.ok((await jog(100)).livre_ate, "o primeiro lance abre o prazo");
await como(3, "meio"); await erro(`select dar_lance_vitrine(100, 3000, 1000, 2)`, /maior lance é de 3000/);
await q(`select dar_lance_vitrine(100, 3000, 1100, 1)`); // mesmo valor, salário maior: passa à frente
assert.equal(await q(`select folha_prometida(3) as f`).then(r => r[0].f), 1100, "lance na frente conta na folha prometida");
assert.equal(await q(`select folha_prometida(2) as f`).then(r => r[0].f), 0);
await como(2, "meio"); await q(`select dar_lance_vitrine(101, 3200, 800, 1)`); // um lance no 101, para ele ficar na virada

// fim do prazo com a janela fechada: espera; com ela aberta, leva o maior lance e o valor vai para o fundo
await q(`update ligas set fundo_taca = 1000`);
await db.exec(`select set_config('trem.vitrine', '1', false); update jogadores set livre_ate = now() - interval '1 minute' where id = 100; select set_config('trem.vitrine', '', false);`);
