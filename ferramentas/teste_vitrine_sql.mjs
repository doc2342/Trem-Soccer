j = await jog(100);
assert.equal(j.clube_id, 3); assert.equal(j.salario, 1100); assert.equal(j.contrato_ate, 4); assert.equal(j.vitrine_minimo, null); assert.equal(j.livre_ate, null);
assert.equal((await q(`select caixa from financas where clube_id = 3`))[0].caixa, 6000);
assert.equal((await q(`select fundo_taca from ligas`))[0].fundo_taca, 4000);
assert.deepEqual(await q(`select tipo, valor from fundo_resumo where tipo = 'vitrine'`), [{ tipo: "vitrine", valor: 3000 }]);
assert.deepEqual(await q(`select tipo, de_clube::int, para_clube::int, valor from transferencias`), [{ tipo: "vitrine", de_clube: +vit, para_clube: 3, valor: 3000 }]);
assert.equal((await q(`select count(*)::int as n from ofertas_livres where jogador_id = 100`))[0].n, 0);

